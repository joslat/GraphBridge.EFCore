    [Fact]
    public void Organization_emits_explicit_application_identity_roles_restrict_and_calendar_conversion()
    {
        var result = GraphCSharpEmitter.Generate(Organization());
        Assert.True(result.Success);
        Assert.Empty(result.Diagnostics);
        Assert.Equal("Example.Organization.OrganizationContext", result.ContextTypeName);
        Assert.Equal(["Context.g.cs", "Entities.g.cs", "GraphIris.g.cs", "GraphModelConfiguration.g.cs"], result.Files.Select(file => file.RelativePath));
