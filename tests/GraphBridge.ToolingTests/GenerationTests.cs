    [Fact]
    public void Diagnostics_are_deterministic_and_errors_never_return_partial_source()
    {
        var first = Node("GraphIris", "bad-label");
        var second = Node("Context", "bad-label");
        var result = GraphCSharpEmitter.Generate(new("Bad..Namespace", "Context", [first, second], []));
        var reversed = GraphCSharpEmitter.Generate(new("Bad..Namespace", "Context", [second, first], []));
        Assert.False(result.Success);
        Assert.Empty(result.Files);
        Assert.Null(result.ContextTypeName);
        Assert.Equal(result.Diagnostics, reversed.Diagnostics);
    }

    private static void Error(GraphSourceGenerationResult result, string code)
    {
        Assert.False(result.Success);
        Assert.Contains(result.Diagnostics, diagnostic => diagnostic.Code == code && diagnostic.Severity == GraphGenerationSeverity.Error);
        Assert.Empty(result.Files);
    }
    private static string File(GraphSourceGenerationResult result, string name)
        => Assert.Single(result.Files, file => file.RelativePath == name).Content;
    private static GraphPropertyDefinition Id(string name = "Id") => new(name, null, name, GraphScalarType.Guid, true, GraphScalarConversion.GuidString);
    private static GraphNodeDefinition Node(string name, string label) => new(name, null, label, [Id()], ["Id"], GraphDeletionPolicy.Restrict);
    internal static GraphGenerationModel Organization()
    {
        var person = new GraphNodeDefinition("Person", "https://example.org/org#Person", "Person", [Id(),
            new("Name", "https://example.org/org#name", "name", GraphScalarType.String, true, GraphScalarConversion.Native)], ["Id"], GraphDeletionPolicy.Restrict);
        var organization = new GraphNodeDefinition("Organization", "https://example.org/org#Organization", "Organization", [Id()], ["Id"], GraphDeletionPolicy.Restrict);
        var edge = new GraphIdentifiedEdgeDefinition("Employment", "https://example.org/org#worksFor", "WORKS_FOR",
            [Id("EmploymentId"), Id("PersonId"), Id("OrganizationId"),
             new("Role", null, "role", GraphScalarType.String, true, GraphScalarConversion.Native),
             new("ValidFrom", null, "valid_from", GraphScalarType.DateOnly, true, GraphScalarConversion.DateOnlyIsoString),
             new("ValidTo", null, "valid_to", GraphScalarType.DateOnly, false, GraphScalarConversion.DateOnlyIsoString)],
            "EmploymentId", new("Person", "Person", ["PersonId"], GraphDeletionPolicy.Restrict),
            new("Organization", "Organization", ["OrganizationId"], GraphDeletionPolicy.Restrict), GraphEdgeDirection.SourceToTarget);
        return new("Example.Organization", "OrganizationContext", [person, organization], [edge]);
    }
