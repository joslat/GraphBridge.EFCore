    [Fact]
    public void Input_order_culture_and_repeated_generation_do_not_change_source_bytes()
    {
        var model = Organization();
        var shuffled = new GraphGenerationModel(model.Namespace, model.ContextName,
            model.Nodes.Reverse().Select(node => new GraphNodeDefinition(node.ClrName, node.Iri, node.Label,
                node.Properties.Reverse(), node.KeyProperties, node.Deletion)),
            model.IdentifiedEdges.Select(edge => new GraphIdentifiedEdgeDefinition(edge.ClrName, edge.Iri, edge.RelationshipType,
                edge.Properties.Reverse(), edge.KeyProperty, edge.Source, edge.Target, edge.Direction)).Reverse());
        var expected = GraphCSharpEmitter.Generate(model);
        var originalCulture = System.Globalization.CultureInfo.CurrentCulture;
        try
        {
            System.Globalization.CultureInfo.CurrentCulture = System.Globalization.CultureInfo.GetCultureInfo("tr-TR");
            var actual = GraphCSharpEmitter.Generate(shuffled);
            Assert.Equal(expected.Files, actual.Files);
            Assert.Equal(expected.Diagnostics, actual.Diagnostics);
            Assert.Equal(actual.Files, GraphCSharpEmitter.Generate(shuffled).Files);
        }
        finally { System.Globalization.CultureInfo.CurrentCulture = originalCulture; }
        Assert.All(expected.Files, file =>
        {
            Assert.DoesNotContain('\r', file.Content);
            Assert.EndsWith("\n", file.Content);
            Assert.DoesNotContain("C:\\", file.Content);
            Assert.StartsWith("// <auto-generated />\n// GraphBridge.Tooling generator contract 1.\n", file.Content);
        });
    }

    [Fact]
    public void Definitions_copy_all_input_collections_and_expose_readonly_lists()
    {
        var properties = new List<GraphPropertyDefinition> { Id() };
        var keys = new List<string> { "Id" };
        var node = new GraphNodeDefinition("Person", null, "Person", properties, keys, GraphDeletionPolicy.Restrict);
        var nodes = new List<GraphNodeDefinition> { node };
        var model = new GraphGenerationModel("Example", "Context", nodes, []);
        var slots = new List<string> { "PersonId" };
        var endpoint = new GraphEndpointDefinition("Person", "Person", slots, GraphDeletionPolicy.Restrict);
        properties.Clear(); keys.Clear(); nodes.Clear(); slots.Clear();
        Assert.Single(model.Nodes);
        Assert.Single(node.Properties);
        Assert.Equal("Id", Assert.Single(node.KeyProperties));
        Assert.Equal("PersonId", Assert.Single(endpoint.ForeignKeyProperties));
        Assert.Throws<NotSupportedException>(() => ((IList<GraphNodeDefinition>)model.Nodes).Clear());
    }

