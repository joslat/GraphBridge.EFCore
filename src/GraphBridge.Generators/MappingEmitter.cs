using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace GraphBridge.Generators;

internal static class MappingEmitter
{
    internal static string Emit(MappingContract model)
    {
        var json = ExpectedWitness.Write(model);
        var text = new StringBuilder("// <auto-generated />\n// GraphBridge.Generators contract 1; EF Core 10.0.12 storage witness schema 1.\n#nullable enable\nusing Microsoft.EntityFrameworkCore;\nusing Microsoft.EntityFrameworkCore.Metadata;\n\n");
        if (!model.Owner.ContainingNamespace.IsGlobalNamespace)
            text.Append("namespace ").Append(model.Owner.ContainingNamespace.ToDisplayString()).Append(";\n\n");
        text.Append(model.Owner.DeclaredAccessibility == Accessibility.Public ? "public" : "internal")
            .Append(" static partial class ").Append(Id(model.Owner.Name)).Append("\n{\n")
            .Append("    public const string Fingerprint = ").Append(Literal(ExpectedWitness.Hash(json))).Append(";\n")
            .Append("    public const string ExpectedCanonicalJson = ").Append(Literal(json)).Append(";\n\n")
            .Append("    public static void Verify(global::Microsoft.EntityFrameworkCore.Metadata.IModel finalizedModel)\n    {\n")
            .Append("        var actual = global::GraphBridge.EntityFrameworkCore.Schema.GraphSchemaManifest.Create(finalizedModel);\n")
            .Append("        if (!global::System.String.Equals(Fingerprint, actual.Fingerprint, global::System.StringComparison.Ordinal))\n")
            .Append("            throw new global::System.InvalidOperationException(\"Generated graph mapping differs from the finalized EF storage model. Expected \" + Fingerprint + \"; actual \" + actual.Fingerprint + \".\");\n    }\n\n")
            .Append("    public static void Apply(global::Microsoft.EntityFrameworkCore.ModelBuilder modelBuilder)\n    {\n")
            .Append("        global::System.ArgumentNullException.ThrowIfNull(modelBuilder);\n");
        foreach (var entity in model.Entities.OrderBy(e => e.Edge).ThenBy(e => e.Symbol.ToDisplayString(), StringComparer.Ordinal))
        {
            text.Append("        modelBuilder.Entity<").Append(Type(entity.Symbol)).Append(">(entity =>\n        {\n");
            if (!entity.Edge) text.Append("            entity.ToGraphNode(").Append(Literal(entity.Token)).Append(");\n");
            foreach (var ignored in entity.Ignored.OrderBy(n => n, StringComparer.Ordinal))
                text.Append("            entity.Ignore(").Append(Literal(ignored)).Append(");\n");
            foreach (var property in entity.Properties.OrderBy(p => p.Symbol.Name, StringComparer.Ordinal))
            {
                text.Append("            {\n                var property = entity.Property<").Append(Type(property.Symbol.Type)).Append(">(")
                    .Append(Literal(property.Symbol.Name)).Append(").HasGraphPropertyName(").Append(Literal(property.Name))
                    .Append(").IsRequired(").Append(property.Required ? "true" : "false").Append(").ValueGeneratedNever()");
                if (property.Conversion == 2)
                    text.Append(".HasConversion(new global::Microsoft.EntityFrameworkCore.Storage.ValueConversion.ValueConverter<global::System.DateOnly, string>(")
                        .Append("date => date.ToString(\"yyyy-MM-dd\", global::System.Globalization.CultureInfo.InvariantCulture), ")
                        .Append("value => global::System.DateOnly.ParseExact(value, \"yyyy-MM-dd\", global::System.Globalization.CultureInfo.InvariantCulture)))");
                if (property.Concurrency == 1) text.Append(".IsConcurrencyToken()");
                if (property.Concurrency == 2) text.Append(".IsRowVersion()");
                text.Append(";\n                property.Metadata.SetBeforeSaveBehavior(global::Microsoft.EntityFrameworkCore.Metadata.PropertySaveBehavior.")
                    .Append(property.Concurrency == 2 ? "Ignore" : "Save").Append(");\n")
                    .Append("                property.Metadata.SetAfterSaveBehavior(global::Microsoft.EntityFrameworkCore.Metadata.PropertySaveBehavior.")
                    .Append(property.Concurrency == 2 ? "Ignore" : entity.Keys.Contains(property.Symbol.Name, StringComparer.Ordinal) ? "Throw" : "Save")
                    .Append(");\n            }\n");
            }
            text.Append("            entity.HasKey(").Append(Names(entity.Keys)).Append(");\n");
            if (entity.Edge)
            {
                Endpoint(entity.Source!); Endpoint(entity.Target!);
                text.Append("            entity.ToGraphIdentifiedRelationship(").Append(Literal(entity.Token)).Append(", ")
                    .Append(Literal(entity.Keys[0])).Append(", ").Append(Names(entity.Source!.Keys)).Append(", ").Append(Names(entity.Target!.Keys)).Append(");\n");
            }
            text.Append("        });\n");
        }
        text.Append("    }\n\n    public static class Identifiers\n    {\n");
        // Stable type names need not be unique across CLR namespaces; encode full metadata names in constant container names.
        foreach (var entity in model.Entities)
        {
            text.Append("        public static class ").Append(Container(entity.Symbol)).Append("\n        {\n")
                .Append("            public const string ").Append(entity.Edge ? "RelationshipType" : "Label").Append(" = ").Append(Literal(entity.Token)).Append(";\n");
            if (entity.Iri is not null) text.Append("            public const string Iri = ").Append(Literal(entity.Iri)).Append(";\n");
            text.Append("            public static class Properties\n            {\n");
            foreach (var property in entity.Properties.OrderBy(p => p.Symbol.Name, StringComparer.Ordinal))
                text.Append("                public const string ").Append(Id("P_" + property.Symbol.Name)).Append(" = ").Append(Literal(property.Name)).Append(";\n");
            text.Append("            }\n            public static class Iris\n            {\n");
            foreach (var property in entity.Properties.Where(p => p.Iri is not null).OrderBy(p => p.Symbol.Name, StringComparer.Ordinal))
                text.Append("                public const string ").Append(Id("P_" + property.Symbol.Name)).Append(" = ").Append(Literal(property.Iri!)).Append(";\n");
            text.Append("            }\n        }\n");
        }
        return text.Append("    }\n}\n").ToString();

        void Endpoint(EndpointContract endpoint)
            => text.Append("            entity.HasOne<").Append(Type(endpoint.Node)).Append(">(").Append(Literal(endpoint.Symbol.Name))
                .Append(").WithMany().HasForeignKey(").Append(Names(endpoint.Keys))
                .Append(").OnDelete(global::Microsoft.EntityFrameworkCore.DeleteBehavior.Restrict).IsRequired();\n");
    }
    private static string Container(INamedTypeSymbol symbol) => "Entity_" + ExpectedWitness.Hash(symbol.ToDisplayString()).Substring(0, 16);
    private static string Names(IEnumerable<string> names) => "new string[] { " + string.Join(", ", names.Select(Literal)) + " }";
    private static string Type(ITypeSymbol symbol) => symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier));
    private static string Id(string name) => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(name) != SyntaxKind.None ? "@" + name : name;
    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}
