using System.Text;

namespace GraphBridge.Tooling.Generation;

/// <summary>Emits reviewable source only. It does not compile code, access a database, or author a runtime manifest.</summary>
public static class GraphCSharpEmitter
{
    public static GraphSourceGenerationResult Generate(GraphGenerationModel model)
    {
        ArgumentNullException.ThrowIfNull(model);
        var diagnostics = GraphGenerationValidation.Validate(model);
        if (diagnostics.Any(value => value.Severity == GraphGenerationSeverity.Error))
            return new([], diagnostics, null);
        var writer = new Emitter(model);
        return new([
            new("Entities.g.cs", writer.Entities()),
            new("Context.g.cs", writer.Context()),
            new("GraphModelConfiguration.g.cs", writer.Configuration()),
            new("GraphIris.g.cs", writer.Iris())
        ], diagnostics, GraphCSharpNames.ReflectionNamespace(model.Namespace) + "." + GraphCSharpNames.Clr(model.ContextName));
    }

    private sealed class Emitter(GraphGenerationModel model)
    {
        private IEnumerable<GraphNodeDefinition> Nodes => model.Nodes.OrderBy(node => node.ClrName, StringComparer.Ordinal);
        private IEnumerable<GraphIdentifiedEdgeDefinition> Edges => model.IdentifiedEdges.OrderBy(edge => edge.ClrName, StringComparer.Ordinal);
        private string Qualified(string name) => "global::" + GraphCSharpNames.Namespace(model.Namespace) + "." + GraphCSharpNames.Identifier(name);
        private static string Id(string name) => GraphCSharpNames.Identifier(name);
        private static string Literal(string value) => GraphCSharpNames.Literal(value);
        private static string PropertyNames(IEnumerable<string> names)
            => "new[] { " + string.Join(", ", names.Select(name => Literal(GraphCSharpNames.Clr(name)))) + " }";

        private StringBuilder Start(bool efUsing = false)
        {
            var text = new StringBuilder("// <auto-generated />\n// GraphBridge.Tooling generator contract 1.\n");
            var iris = model.Nodes.Select(node => node.Iri).Concat(model.IdentifiedEdges.Select(edge => edge.Iri))
                .Concat(model.Nodes.SelectMany(node => node.Properties).Concat(model.IdentifiedEdges.SelectMany(edge => edge.Properties))
                    .Select(property => property.Iri)).OfType<string>().Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal);
            foreach (var iri in iris) text.Append("// Source IRI: ").Append(Literal(iri)).Append('\n');
            text.Append("#nullable enable\n\n");
            if (efUsing) text.Append("using Microsoft.EntityFrameworkCore;\n\n");
            return text.Append("namespace ").Append(GraphCSharpNames.Namespace(model.Namespace)).Append(";\n\n");
        }

        internal string Entities()
        {
            var text = Start();
            foreach (var node in Nodes) Entity(text, node.ClrName, node.Properties, []);
            foreach (var edge in Edges) Entity(text, edge.ClrName, edge.Properties, [edge.Source, edge.Target]);
            return text.ToString().TrimEnd('\n') + "\n";
        }

        private void Entity(StringBuilder text, string name, IEnumerable<GraphPropertyDefinition> properties,
            IEnumerable<GraphEndpointDefinition> endpoints)
        {
            text.Append("public partial class ").Append(Id(name)).Append("\n{\n");
            foreach (var property in properties.OrderBy(property => property.ClrName, StringComparer.Ordinal))
            {
                text.Append("    public ").Append(ClrType(property)).Append(' ').Append(Id(property.ClrName)).Append(" { get; set; }");
                if (property.ScalarType == GraphScalarType.String && property.IsRequired) text.Append(" = string.Empty;");
                text.Append('\n');
            }
            foreach (var endpoint in endpoints)
                text.Append("    public ").Append(Qualified(endpoint.NodeClrName)).Append(' ').Append(Id(endpoint.NavigationName))
                    .Append(" { get; set; } = null!;\n");
            text.Append("}\n\n");
        }

        internal string Context()
        {
            var text = Start();
            text.Append("public partial class ").Append(Id(model.ContextName)).Append(" : global::Microsoft.EntityFrameworkCore.DbContext\n{\n")
                .Append("    public ").Append(Id(model.ContextName)).Append("(global::Microsoft.EntityFrameworkCore.DbContextOptions options) : base(options) { }\n\n");
            foreach (var name in model.Nodes.Select(node => node.ClrName).Concat(model.IdentifiedEdges.Select(edge => edge.ClrName)).Order(StringComparer.Ordinal))
                text.Append("    public global::Microsoft.EntityFrameworkCore.DbSet<").Append(Qualified(name)).Append("> ")
                    .Append(Id(GraphCSharpNames.Clr(name) + "Set")).Append(" => Set<").Append(Qualified(name)).Append(">();\n");
            return text.Append("\n    protected override void OnModelCreating(global::Microsoft.EntityFrameworkCore.ModelBuilder modelBuilder)\n    {\n")
                .Append("        ").Append(Qualified("GraphModelConfiguration")).Append(".Apply(modelBuilder);\n")
                .Append("        OnModelCreatingPartial(modelBuilder);\n    }\n\n")
                .Append("    partial void OnModelCreatingPartial(global::Microsoft.EntityFrameworkCore.ModelBuilder modelBuilder);\n}\n").ToString();
        }

        internal string Configuration()
        {
            var text = Start(efUsing: true);
            text.Append("public static class GraphModelConfiguration\n{\n");
            if (model.Nodes.SelectMany(node => node.Properties).Concat(model.IdentifiedEdges.SelectMany(edge => edge.Properties))
                .Any(property => property.Conversion == GraphScalarConversion.DateOnlyIsoString))
                text.Append("    // Calendar dates only: invariant yyyy-MM-dd, no time or timezone conversion.\n")
                    .Append("    private static readonly global::Microsoft.EntityFrameworkCore.Storage.ValueConversion.ValueConverter DateOnlyIsoString =\n")
                    .Append("        new global::Microsoft.EntityFrameworkCore.Storage.ValueConversion.ValueConverter<global::System.DateOnly, string>(\n")
                    .Append("            date => date.ToString(\"yyyy-MM-dd\", global::System.Globalization.CultureInfo.InvariantCulture),\n")
                    .Append("            text => global::System.DateOnly.ParseExact(text, \"yyyy-MM-dd\", global::System.Globalization.CultureInfo.InvariantCulture));\n\n");
            text.Append("    public static void Apply(global::Microsoft.EntityFrameworkCore.ModelBuilder modelBuilder)\n    {\n")
                .Append("        global::System.ArgumentNullException.ThrowIfNull(modelBuilder);\n")
                .Append("        // GuidString explicitly selects GraphBridge's canonical Guid-to-D-string mapping.\n");
            foreach (var node in Nodes)
            {
                text.Append("        modelBuilder.Entity<").Append(Qualified(node.ClrName)).Append(">(entity =>\n        {\n")
                    .Append("            entity.ToGraphNode(").Append(Literal(node.Label)).Append(");\n");
                Properties(text, node.Properties);
                text.Append("            entity.HasKey(").Append(PropertyNames(node.KeyProperties)).Append(");\n        });\n");
            }
            foreach (var edge in Edges)
            {
                text.Append("        modelBuilder.Entity<").Append(Qualified(edge.ClrName)).Append(">(entity =>\n        {\n");
                Properties(text, edge.Properties);
                text.Append("            entity.HasKey(").Append(Literal(GraphCSharpNames.Clr(edge.KeyProperty))).Append(");\n");
                Endpoint(text, edge.Source);
                Endpoint(text, edge.Target);
                text.Append("            entity.ToGraphIdentifiedRelationship(").Append(Literal(edge.RelationshipType)).Append(", ")
                    .Append(Literal(GraphCSharpNames.Clr(edge.KeyProperty))).Append(", ")
                    .Append(PropertyNames(edge.Source.ForeignKeyProperties)).Append(", ").Append(PropertyNames(edge.Target.ForeignKeyProperties)).Append(");\n        });\n");
            }
            return text.Append("    }\n}\n").ToString();
        }

        private static void Properties(StringBuilder text, IEnumerable<GraphPropertyDefinition> properties)
        {
            foreach (var property in properties.OrderBy(property => property.ClrName, StringComparer.Ordinal))
            {
                text.Append("            entity.Property<").Append(ClrType(property)).Append(">(").Append(Literal(GraphCSharpNames.Clr(property.ClrName)))
                    .Append(").HasGraphPropertyName(").Append(Literal(property.StoreName)).Append(").IsRequired(")
                    .Append(property.IsRequired ? "true" : "false").Append(").ValueGeneratedNever()");
                if (property.Conversion == GraphScalarConversion.DateOnlyIsoString) text.Append(".HasConversion(DateOnlyIsoString)");
                if (property.Concurrency == GraphConcurrencyMode.OriginalValue) text.Append(".IsConcurrencyToken()");
                if (property.Concurrency == GraphConcurrencyMode.IncrementingInt64) text.Append(".IsRowVersion()");
                text.Append(";\n");
            }
        }

        private void Endpoint(StringBuilder text, GraphEndpointDefinition endpoint)
            => text.Append("            entity.HasOne<").Append(Qualified(endpoint.NodeClrName)).Append(">(")
                .Append(Literal(GraphCSharpNames.Clr(endpoint.NavigationName))).Append(").WithMany().HasForeignKey(")
                .Append(PropertyNames(endpoint.ForeignKeyProperties)).Append(").OnDelete(global::Microsoft.EntityFrameworkCore.DeleteBehavior.Restrict).IsRequired();\n");

        internal string Iris()
        {
            var text = Start().Append("public static class GraphIris\n{\n");
            foreach (var node in Nodes) Iris(text, node.ClrName, node.Iri, node.Properties);
            foreach (var edge in Edges) Iris(text, edge.ClrName, edge.Iri, edge.Properties);
            return text.Append("}\n").ToString();
        }

        private static void Iris(StringBuilder text, string name, string? iri, IEnumerable<GraphPropertyDefinition> properties)
        {
            text.Append("    public static class ").Append(Id(name)).Append("\n    {\n");
            if (iri is not null) text.Append("        public const string Type = ").Append(Literal(iri)).Append(";\n");
            foreach (var property in properties.Where(property => property.Iri is not null).OrderBy(property => property.ClrName, StringComparer.Ordinal))
                text.Append("        public const string ").Append(Id(property.ClrName)).Append(" = ").Append(Literal(property.Iri!)).Append(";\n");
            text.Append("    }\n");
        }

        private static string ClrType(GraphPropertyDefinition property)
            => (property.ScalarType switch
            {
                GraphScalarType.String => "string",
                GraphScalarType.Boolean => "bool",
                GraphScalarType.Int32 => "int",
                GraphScalarType.Int64 => "long",
                GraphScalarType.Double => "double",
                GraphScalarType.Guid => "global::System.Guid",
                GraphScalarType.DateOnly => "global::System.DateOnly",
                _ => throw new InvalidOperationException("Generation requires validated scalar types.")
            }) + (property.IsRequired ? "" : "?");
    }
}
